CREATE TABLE IF NOT EXISTS travel_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title TEXT NOT NULL, destination TEXT NOT NULL,
 start_date DATE NOT NULL, end_date DATE,
 summary TEXT NOT NULL DEFAULT '', body TEXT NOT NULL DEFAULT '', actual_cost TEXT NOT NULL DEFAULT '',
 photos JSONB NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(photos)='array' AND jsonb_array_length(photos)<=30),
 cover TEXT NOT NULL DEFAULT '/static/assets/lake.jpg',
 guide_id BIGINT REFERENCES guides(id) ON DELETE SET NULL, guide_day INTEGER CHECK(guide_day BETWEEN 1 AND 365),
 status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('public','private','draft')),
 revision INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(), deleted_at TIMESTAMPTZ,
 CHECK(end_date IS NULL OR end_date>=start_date),
 CHECK(status<>'public' OR length(trim(body))>0 OR jsonb_array_length(photos)>0)
);
CREATE INDEX IF NOT EXISTS travel_records_timeline ON travel_records(start_date DESC,id DESC) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS travel_records_guide ON travel_records(guide_id);
CREATE INDEX IF NOT EXISTS travel_records_photos ON travel_records USING GIN(photos);
