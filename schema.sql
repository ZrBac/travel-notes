 cancel_requested BOOLEAN NOT NULL DEFAULT false,
 request JSONB NOT NULL DEFAULT '{}', result TEXT NOT NULL DEFAULT '', report JSONB NOT NULL DEFAULT '{}',
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_tasks_queue ON agent_tasks(id) WHERE status='queued';
